def build_cursor(home: Path) -> Path:
    path = cursor.db_paths(home)[0]
    path.parent.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(path)
    con.execute("CREATE TABLE ItemTable (key TEXT UNIQUE ON CONFLICT REPLACE, value BLOB)")
    con.execute("CREATE TABLE cursorDiskKV (key TEXT UNIQUE ON CONFLICT REPLACE, value BLOB)")
    model = "claude-4.5-opus-high-thinking"
    rows = [
        ("composerData:c1", {"composerId": "c1", "createdAt": int(epoch("03-20 12:00:00") * 1000),
                             "modelConfig": {"modelName": model}, "totalLinesAdded": 40, "totalLinesRemoved": 4}),
        ("bubbleId:c1:b1", {"type": 1, "createdAt": iso("03-20 12:00:05"), "text": "make it faster"}),
        ("bubbleId:c1:b2", {"type": 2, "createdAt": iso("03-20 12:00:30"),
                            "tokenCount": {"inputTokens": 900, "outputTokens": 90}, "modelInfo": {"modelName": model}}),
        ("bubbleId:c1:b3", {"type": 2, "createdAt": None, "modelInfo": {"modelName": "default"}}),
        ("composerData:c0", {"composerId": "c0", "createdAt": int(epoch("2025-06-01 00:00:00") * 1000),
                             "totalLinesAdded": 999}),
        ("bubbleId:c0:b9", {"type": 1, "createdAt": iso("2025-06-01 00:00:05")}),
        ("bubbleId:bad", {"type": 1, "createdAt": iso("03-20 12:00:05")}),
    ]
    con.executemany("INSERT INTO cursorDiskKV VALUES (?, ?)", [(k, json.dumps(v)) for k, v in rows])
    con.execute("INSERT INTO cursorDiskKV VALUES (?, ?)", ("bubbleId:c1:b4", "not json"))
