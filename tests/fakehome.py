def usage(i=0, o=0, cr=0, cw=0) -> dict:
    return {"input_tokens": i, "output_tokens": o, "cache_read_input_tokens": cr, "cache_creation_input_tokens": cw}


def c_user(stamp, content, cwd=CWD_A, **extra) -> dict:
    return {"type": "user", "timestamp": iso(stamp), "cwd": cwd, "entrypoint": "claude-desktop",
            "message": {"role": "user", "content": content}, **extra}


def c_assistant(stamp, mid, blocks, use, model="claude-opus-5-5", cwd=CWD_A, **extra) -> dict:
    return {"type": "assistant", "timestamp": iso(stamp), "cwd": cwd, "requestId": "req-" + mid,
            "message": {"id": mid, "model": model, "role": "assistant", "content": blocks, "usage": use,
                        "stop_reason": "tool_use"}, **extra}


def tool_use(tid, name) -> dict:
    return {"type": "tool_use", "id": tid, "name": name, "input": {}}


def text(value) -> dict:
    return {"type": "text", "text": value}


def queued(stamp, prompt, mode="prompt", origin=None) -> dict:
    attachment = {"type": "queued_command", "prompt": prompt, "commandMode": mode, "timestamp": iso(stamp)}
    if origin is not None:
        attachment["origin"] = origin
    return {"type": "attachment", "timestamp": iso(stamp), "cwd": CWD_A, "attachment": attachment}


