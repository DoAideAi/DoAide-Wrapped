def x(stamp, kind, payload) -> dict:
    return {"timestamp": iso(stamp), "type": kind, "payload": payload}


def x_user(stamp, value) -> dict:
    return x(stamp, "response_item", {"type": "message", "role": "user",
                                      "content": [{"type": "input_text", "text": value}]})


def x_reply(stamp) -> dict:
    return x(stamp, "response_item", {"type": "message", "role": "assistant",
                                      "content": [{"type": "output_text", "text": "done"}]})


def x_usage(i, cached, o, total, reasoning=0) -> dict:
    return {"input_tokens": i, "cached_input_tokens": cached, "cache_write_input_tokens": 0, "output_tokens": o,
            "reasoning_output_tokens": reasoning, "total_tokens": total}


