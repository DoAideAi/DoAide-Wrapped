def iso(stamp: str) -> str:
    """'03-14 23:10:00' -> '2026-03-14T23:10:00.000Z'; a leading year is kept ('2025-12-31 10:00:00')."""
    day, clock = stamp.split(" ")
    if day.count("-") == 1:
        day = "2026-" + day
    return f"{day}T{clock}.000Z"


def epoch(stamp: str) -> float:
    return datetime.fromisoformat(iso(stamp).replace("Z", "+00:00")).timestamp()


def write_jsonl(path: Path, events) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        for event in events:
            fh.write(event if isinstance(event, str) else json.dumps(event))
            fh.write("\n")
    return path


